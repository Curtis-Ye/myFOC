// 正弦函数
static inline int16_t sin_q15(uint16_t angle)
{
    uint16_t idx = angle >> SIN_TAB_SHIFT;     // 0 ~ 1023
    uint16_t frac = angle & SIN_TAB_FRAC_MASK; // 0 ~ 63

    int32_t s0 = sin_tab[idx];
    int32_t s1 = sin_tab[idx + 1];

    // 线性插值，加 32 实现四舍五入
    int32_t sum = s0 * (64 - frac) + s1 * frac;
    return (int16_t)((sum + 32) >> 6);
}

// 余弦函数
static inline int16_t cos_q15(uint16_t angle)
{
    // cos(θ) = sin(θ + 90°)
    // 90° 对应 16384
    return sin_q15((uint16_t)(angle + 16384));
}

// 限幅
static inline int16_t sat_q15(int32_t x)
{
    if (x > 32767)
        return 32767;
    if (x < -32768)
        return -32768;
    return (int16_t)x;
}

static inline uint16_t angle_reverse(float angle)
{
    // 归一化到 [0, 360)，避免浮点除法和越界
    while (angle >= 360.0f)
        angle -= 360.0f;
    while (angle < 0.0f)
        angle += 360.0f;

    // 65536 / 360 = 182.0444...
    return (uint16_t)((uint32_t)(angle * (65536.0f / 360.0f)) & 0xFFFF);
}

// 帕克逆变换
ElectricAngle park_inverse(uint16_t angle, int16_t Uq, int16_t Ud)
{
    int16_t s = sin_q15(angle);
    int16_t c = cos_q15(angle);

    // 注意：必须用 int32_t 承接，结果是带符号的。
    // 若用 uint16_t 承接，负半周会回绕成大正数，再经 sat_q15 被钳到 +32767。
    int32_t alpha = ((int32_t)Ud * c - (int32_t)Uq * s) >> 15;
    int32_t beta = ((int32_t)Uq * c + (int32_t)Ud * s) >> 15;

    ElectricAngle out;
    out.U_alpha = sat_q15(alpha);
    out.U_beta = sat_q15(beta);
    return out;
}

// 克拉克逆变换
ThreePhase clark_inverse(int16_t U_alpha, int16_t U_beta)
{
    // 原文 (-1 / 2) 是整数除法，结果为 0，U_alpha 项被整个丢掉
    int32_t half_alpha = (int32_t)U_alpha / 2;
    // 原文 >> 15 的优先级低于 +，会变成 (a + b) >> 15，必须加括号
    int32_t beta_term = ((int32_t)SQRT3_2_Q15 * (int32_t)U_beta) >> 15;

    ThreePhase out;
    out.Ua = U_alpha;
    out.Ub = sat_q15(-half_alpha + beta_term);
    out.Uc = sat_q15(-half_alpha - beta_term);
    return out;
}

// FOC控制
void FOC_control(float current_angle, int16_t Uq)
{
    uint16_t Angle = angle_reverse(current_angle); // 角度转化Q15对应值
    ElectricAngle electricangle;
    // ThreePhase threephase;
    Duty duty;

    electricangle = park_inverse(Angle, Uq, 0);
    threephase = clark_inverse(electricangle.U_alpha, electricangle.U_beta);

    duty.dutyA = (((int32_t)threephase.Ua + 32768) * ARR) >> 16;
    duty.dutyB = (((int32_t)threephase.Ub + 32768) * ARR) >> 16;
    duty.dutyC = (((int32_t)threephase.Uc + 32768) * ARR) >> 16;

    // 限幅到 [0, ARR]，防止异常值把 CCR 写得比 ARR 还大
    if (duty.dutyA < 0)
        duty.dutyA = 0;
    if (duty.dutyA > ARR)
        duty.dutyA = ARR;
    if (duty.dutyB < 0)
        duty.dutyB = 0;
    if (duty.dutyB > ARR)
        duty.dutyB = ARR;
    if (duty.dutyC < 0)
        duty.dutyC = 0;
    if (duty.dutyC > ARR)
        duty.dutyC = ARR;

    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, duty.dutyA);
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, duty.dutyB);
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_3, duty.dutyC);
}

void FOC_OpenLoop_Update(void)
{
    // 每个调用周期角度增加
    open_loop_elec_angle += 360.0f * open_loop_elec_freq / FOC_CALL_FREQ;

    // 归一化到 0~360
    if (open_loop_elec_angle >= 360.0f)
        open_loop_elec_angle -= 360.0f;

    // 调用 FOC 函数
    FOC_control(open_loop_elec_angle, open_loop_Uq);
}

void foc_calibrate_phase(void)
{
    unsigned short last_angle = 0, positive_counter = 0;
    float angle = 0;

    /* set that there is only a magnetic field on the straight axis */
    // foc_calculate_dutycycle(0, CALI_TORQUE, 0, &u, &v, &w);
    // update_pwm_dutycycle(u, v, w);
    FOC_control(0, open_loop_Uq);
    delayms(1000);

    for (unsigned char counter = 0; counter < 50; ++counter)
    {
        /* measure current motor angle */
        unsigned short current_angle = AS5600_ReadAngle();

        /* judge whether the current angle increases */
        if (current_angle > last_angle)
            positive_counter++;

        /* update last angle as current angle */
        last_angle = current_angle;

        /* set that there is only a magnetic field on the straight axis */
        // foc_calculate_dutycycle(angle, CALI_TORQUE, 0, &u, &v, &w);
        FOC_control(0, open_loop_Uq);
        angle += 0.2f;
        // update_pwm_dutycycle(u, v, w);
        delayms(20);
    }
    for (unsigned char counter = 0; counter < 50; ++counter)
    {
        /* measure current motor angle */
        unsigned short current_angle = AS5600_ReadAngle();

        /* judge whether the current angle decreases */
        if (current_angle < last_angle)
            positive_counter++;

        /* update last angle as current angle */
        last_angle = current_angle;

        /* set that there is only a magnetic field on the straight axis */
        // foc_calculate_dutycycle(angle, CALI_TORQUE, 0, &u, &v, &w);
        FOC_control(0, open_loop_Uq);
        angle -= 0.2f;
        // update_pwm_dutycycle(u, v, w);
        delayms(20);
    }

    /* zero the torque in all directions to release the motor */
    // foc_calculate_dutycycle(0, 0, 0, &u, &v, &w);
    // update_pwm_dutycycle(u, v, w);
    FOC_control(0, 0);
    delayms(300);

    if (positive_counter >= 75)
        phase_sequence = 0;
    else if (positive_counter < 25)
        phase_sequence = 1;
    else
        while (1)
            ;
}
